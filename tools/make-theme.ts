// @ts-nocheck - runs under node, which the project does not carry types for
/**
 * Generates src/theme-terminal.css: the terminal theme.
 *
 * Every rule in style.css that sets a colour is copied under
 * html[data-theme="terminal"] with its colours moved into the phosphor
 * palette (see src/ui/phosphor.ts), followed by the hand-written layout and
 * flavour in tools/terminal-extra.css. Run with `npm run theme` after
 * changing style.css.
 */

import fs from "node:fs";
import postcss, { type AtRule, type Container, type Rule } from "postcss";
import { COLOR_PATTERN, phosphorValue } from "../src/ui/phosphor";

const ROOT = 'html[data-theme="terminal"]';
const source = fs.readFileSync("src/style.css", "utf8");
const extra = fs.readFileSync("tools/terminal-extra.css", "utf8");
const parsed = postcss.parse(source);

const prefix = (selector: string): string =>
  selector
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean)
    .map((part) => (part === ":root" ? ROOT : `${ROOT} ${part}`))
    .join(",\n");

const out: string[] = [];
let emitted = 0;

parsed.walkRules((rule: Rule) => {
  // Keyframes steps are not selectors.
  let ancestor: Container | undefined = rule.parent;
  const wrappers: AtRule[] = [];
  while (ancestor && ancestor.type === "atrule") {
    const at = ancestor as AtRule;
    if (/keyframes/i.test(at.name)) return;
    wrappers.unshift(at);
    ancestor = at.parent as Container | undefined;
  }

  const lines: string[] = [];
  rule.walkDecls((decl) => {
    COLOR_PATTERN.lastIndex = 0;
    if (!COLOR_PATTERN.test(decl.value)) return;
    COLOR_PATTERN.lastIndex = 0;
    lines.push(`  ${decl.prop}: ${phosphorValue(decl.value)}${decl.important ? " !important" : ""};`);
  });
  if (!lines.length) return;

  let block = `${prefix(rule.selector)} {\n${lines.join("\n")}\n}`;
  for (const at of wrappers.reverse()) {
    block = `@${at.name} ${at.params} {\n${block.replace(/^/gm, "  ")}\n}`;
  }
  out.push(block);
  emitted++;
});

const header = `/* GENERATED by tools/make-theme.ts from src/style.css and tools/terminal-extra.css.\n   Do not edit: change those and run \`npm run theme\`. (${emitted} derived rules) */\n`;
fs.writeFileSync("src/theme-terminal.css", `${header}\n/* ---- derived: every colour moved into the phosphor palette ---- */\n${out.join("\n")}\n\n/* ---- terminal.extra.css ---- */\n${extra}\n`);
console.log(`terminal theme: ${emitted} rules derived`);
